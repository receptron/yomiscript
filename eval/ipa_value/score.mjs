// Both parts scored into results/summary.md, with a short list of wav files to listen to.
// usage: node score.mjs   (after run.mjs, base.py, synth.mjs accent|mixed, f0.py, asr.py)
import fs from "fs";
import path from "path";
import { AUDIO, RESULTS, readJson } from "./common.mjs";
import { accentReport } from "./score_accent.mjs";
import { mixedReport } from "./score_mixed.mjs";

const LISTEN_ACCENT = ["ame_1", "ame_2", "hashi_1", "hashi_2", "hashi_3", "sake_1", "sake_2", "kami_1", "kami_2"];
const LISTEN_MIXED = ["en_01", "en_05", "en_11", "en_13", "ja_05"];

function listenList() {
  const code = (kind, c, n) => "`" + path.relative(path.join(RESULTS, ".."), path.join(AUDIO, kind, c, n + ".wav")) + "`";
  const row = (kind, conds, n) => `- ${n}: ` + conds.map((c) => code(kind, c, n)).join(", ");
  const lines = ["## To listen to (nobody has listened yet)", "", "Accent (same sentence, four conditions):", ""];
  for (const n of LISTEN_ACCENT) lines.push(row("accent", ["kokoro", "kana_dict", "dict", "claude"], n));
  lines.push("", "Code-switching (Claude's YomiScript, then Claude's kana):", "");
  for (const n of LISTEN_MIXED) lines.push(row("mixed", ["ys_claude", "kana_claude"], n));
  return lines.join("\n");
}

function failures() {
  const F = ["accent", "mixed"].flatMap((k) => readJson(`results/${k}_ys.json`).failed.map((f) => `- ${k}: ${f}`));
  return ["## Not synthesized (the LLM's YomiScript is rejected by the parser)", "", ...(F.length ? F : ["none"])].join("\n");
}

const md = [
  "# eval/ipa_value: results",
  "",
  `Generated by score.mjs on ${new Date().toISOString().slice(0, 10)}. See README.md for the design and what the numbers say.`,
  "",
  await accentReport(),
  "",
  mixedReport(),
  "",
  failures(),
  "",
  listenList(),
  "",
].join("\n");
fs.writeFileSync(path.join(RESULTS, "summary.md"), md);
